"""Import requirements from CSV (an export of Jira, Azure DevOps, a spreadsheet ...).

Format (docs/requirements-import.md, sample samples/requirements.csv): UTF-8, comma-separated,
first row = column names. ``id`` and ``title`` are required; ``description``, ``component``
(or ``feature``), ``priority``, ``criticality``, ``risk`` and ``platforms`` (separated by ``;``)
are optional. Column names are case-insensitive.

The import never edits hand-written files: requirements are written to a file generated by
this module (first line :data:`GENERATED_MARKER`), which a catalog includes with
``include = ["requirements.toml"]``. Test cases and their links to requirements stay in the
hand-written catalog, so re-importing never touches them.

The import is all-or-nothing: one invalid row means nothing is written, and every problem is
listed with its row number and column.
"""

from __future__ import annotations

import csv
import io
import json
from collections.abc import Iterable, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from pydantic import ValidationError

from qualityintel.ingest.errors import IngestError
from qualityintel.models.catalog import Requirement

GENERATED_MARKER = "# Generated by qi requirements import"
MAX_FILE_BYTES = 10 * 1024 * 1024
REQUIRED = ("id", "title")
# CSV column -> Requirement field ("component" is the usual name in issue trackers)
COLUMNS = {
    "id": "id",
    "title": "title",
    "description": "description",
    "component": "feature",
    "feature": "feature",
    "priority": "priority",
    "criticality": "criticality",
    "risk": "risk",
    "platforms": "platforms",
}
# Field order in the generated TOML file (stable, so re-imports give identical files)
FIELD_ORDER = ("id", "title", "description", "feature", "criticality", "priority", "risk", "platforms")


class RequirementsCsvError(IngestError):
    """The CSV file as a whole cannot be used (unreadable, no header, unknown columns ...)."""


@dataclass(frozen=True)
class RowError:
    """A problem in one row. ``row`` is the line number a spreadsheet shows (header = 1)."""

    row: int
    column: str | None
    message: str

    def __str__(self) -> str:
        """``row 5, criticality: Input should be ...``."""
        where = f"row {self.row}" + (f", {self.column}" if self.column else "")
        return f"{where}: {self.message}"


@dataclass
class ParsedCsv:
    """Requirements read from the file and the problems found in its rows."""

    source: str
    requirements: list[Requirement] = field(default_factory=list)
    errors: list[RowError] = field(default_factory=list)
    rows: int = 0


@dataclass
class ImportPlan:
    """What an import would change in the target file.

    Attributes:
        added: Requirements that are not in the target yet.
        changed: ``(before, after, changed field names)`` for requirements whose values differ.
        unchanged: Requirements that are already in the target exactly as in the file.
        kept: Requirements in the target that the file does not mention; they stay (removing
            them could break test-case links, which is a decision for a person).
        conflicts: Ids the file brings that are defined in another catalog file.
        result: The target's requirements after the import: the existing ones in their order
            (updated where changed), then the new ones in file order.
    """

    added: list[Requirement] = field(default_factory=list)
    changed: list[tuple[Requirement, Requirement, tuple[str, ...]]] = field(default_factory=list)
    unchanged: list[Requirement] = field(default_factory=list)
    kept: list[Requirement] = field(default_factory=list)
    conflicts: list[str] = field(default_factory=list)
    result: list[Requirement] = field(default_factory=list)


def read_requirements_csv(path: Path) -> ParsedCsv:
    """Read a requirements CSV file.

    Raises:
        RequirementsCsvError: Unreadable, too large, not UTF-8, empty, no usable header.
    """
    source = path.name
    try:
        size = path.stat().st_size
        if size > MAX_FILE_BYTES:
            raise RequirementsCsvError(
                source, f"file is {size} bytes, more than the limit of {MAX_FILE_BYTES}"
            )
        data = path.read_bytes()
    except OSError as error:
        raise RequirementsCsvError(source, f"cannot be read ({error.strerror or error})") from None
    try:
        # utf-8-sig: spreadsheet programs often write a byte order mark
        text = data.decode("utf-8-sig")
    except UnicodeDecodeError as error:
        raise RequirementsCsvError(
            source, f"is not UTF-8 text (byte {error.start}); save it as CSV UTF-8"
        ) from None
    return parse_requirements_csv(text, source)


def parse_requirements_csv(text: str, source: str = "requirements.csv") -> ParsedCsv:
    """Parse CSV text into requirements and row errors (see the module docstring for the format)."""
    reader = csv.reader(io.StringIO(text, newline=""))
    try:
        header = next(reader)
    except StopIteration:
        raise RequirementsCsvError(source, "file is empty; the first row must name the columns") from None
    except csv.Error as error:
        raise RequirementsCsvError(source, f"not valid CSV ({error})") from None
    columns = _columns(header, source)

    parsed = ParsedCsv(source=source)
    first_row: dict[str, int] = {}
    try:
        for values in reader:
            line = reader.line_num
            if not any(value.strip() for value in values):
                continue  # blank lines are allowed and ignored
            parsed.rows += 1
            if len(values) != len(columns):
                parsed.errors.append(
                    RowError(line, None, f"has {len(values)} values, the header has {len(columns)} columns")
                )
                continue
            requirement = _requirement(dict(zip(columns, values, strict=True)), line, parsed.errors)
            if requirement is None:
                continue
            if requirement.id in first_row:
                parsed.errors.append(
                    RowError(
                        line, "id", f"{requirement.id} is already used in row {first_row[requirement.id]}"
                    )
                )
                continue
            first_row[requirement.id] = line
            parsed.requirements.append(requirement)
    except csv.Error as error:
        raise RequirementsCsvError(source, f"not valid CSV near line {reader.line_num} ({error})") from None
    if parsed.rows == 0:
        raise RequirementsCsvError(source, "has a header but no requirement rows")
    return parsed


def plan_import(
    incoming: Sequence[Requirement], existing: Sequence[Requirement], defined_elsewhere: Iterable[str] = ()
) -> ImportPlan:
    """Compare the file's requirements with the target's (matched by id)."""
    current = {r.id: r for r in existing}
    elsewhere = set(defined_elsewhere)
    plan = ImportPlan()
    updates: dict[str, Requirement] = {}
    for requirement in incoming:
        if requirement.id in elsewhere:
            plan.conflicts.append(requirement.id)
        before = current.get(requirement.id)
        if before is None:
            plan.added.append(requirement)
        elif before == requirement:
            plan.unchanged.append(requirement)
        else:
            fields = tuple(f for f in FIELD_ORDER if getattr(before, f) != getattr(requirement, f))
            plan.changed.append((before, requirement, fields))
            updates[requirement.id] = requirement
    mentioned = {r.id for r in incoming}
    plan.kept = [r for r in existing if r.id not in mentioned]
    plan.result = [updates.get(r.id, r) for r in existing] + plan.added
    return plan


def render_requirements_toml(requirements: Iterable[Requirement], source_name: str) -> str:
    """The generated requirements file: marker, a note on where it comes from, one entry each."""
    lines = [
        GENERATED_MARKER,
        f"# from {source_name}. Do not edit by hand: change the CSV and import it again.",
        "# Test cases and their links to these requirements live in the catalog that includes this file.",
    ]
    for requirement in requirements:
        lines += ["", "[[requirement]]"]
        for name in FIELD_ORDER:
            value = getattr(requirement, name)
            if value is None or value == ():
                continue
            value = getattr(value, "value", value)
            lines.append(f"{name} = {_toml_value(value)}")
    return "\n".join(lines) + "\n"


def is_generated(path: Path) -> bool:
    """True when the file does not exist yet or was written by this module."""
    if not path.exists():
        return True
    with path.open(encoding="utf-8", errors="replace") as handle:
        return handle.readline().rstrip("\r\n") == GENERATED_MARKER


def _columns(header: list[str], source: str) -> list[str]:
    """Map header cells to field names; unknown, missing or duplicate columns stop the import."""
    names = [cell.strip().lower().replace(" ", "_") for cell in header]
    unknown = [name for name in names if name not in COLUMNS]
    if unknown:
        raise RequirementsCsvError(
            source, f"unknown column(s): {', '.join(unknown)}; allowed: {', '.join(COLUMNS)}"
        )
    fields = [COLUMNS[name] for name in names]
    doubled = sorted({f for f in fields if fields.count(f) > 1})
    if doubled:
        raise RequirementsCsvError(
            source, f"column(s) given twice: {', '.join(doubled)} (component and feature are the same)"
        )
    missing = [name for name in REQUIRED if name not in fields]
    if missing:
        raise RequirementsCsvError(source, f"missing required column(s): {', '.join(missing)}")
    return fields


def _requirement(cells: dict[str, str], line: int, errors: list[RowError]) -> Requirement | None:
    """Validate one row; problems go to ``errors`` with the column name."""
    data: dict[str, Any] = {}
    for name, raw in cells.items():
        value = raw.strip()
        if not value:
            continue
        if name == "platforms":
            data[name] = [part.strip() for part in value.split(";") if part.strip()]
        elif name in {"priority", "criticality", "risk"}:
            data[name] = value.lower()  # "P1", "Critical" from trackers are accepted
        else:
            data[name] = value
    for required in REQUIRED:
        if required not in data:
            errors.append(RowError(line, required, "is required"))
    if any(e.row == line for e in errors):
        return None
    try:
        return Requirement.model_validate(data)
    except ValidationError as error:
        for problem in error.errors():
            column = str(problem["loc"][0]) if problem["loc"] else None
            errors.append(RowError(line, "component" if column == "feature" else column, problem["msg"]))
        return None


def _toml_value(value: object) -> str:
    """A TOML basic string or array of strings (JSON string escaping is valid TOML)."""
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(json.dumps(str(item), ensure_ascii=False) for item in value) + "]"
    return json.dumps(str(value), ensure_ascii=False)
